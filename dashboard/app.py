import streamlit as st
import json
import os
import pandas as pd
import sys

# Add parent directory to path so we can import core modules
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from core.database import fetch_all_sessions
from core.model import predict_burnout_risk
from core.chatbot import WellnessChatbot

st.set_page_config(page_title="AuraSync AI Telemetry Dashboard", page_icon="✨", layout="wide")

st.title("✨ AuraSync AI - Telemetry & Wellness Dashboard")
st.markdown("Real-time telemetry, ergonomic insights, and historical session logs generated by your AI Coach.")

# Refresh button
if st.button("🔄 Refresh Telemetry Data"):
    st.rerun()

# Layout Columns for Live Session Data
col1, col2 = st.columns(2)

report_file = "session_session_report.json" if os.path.exists("session_session_report.json") else "session_report.json"

if os.path.exists(report_file):
    with open(report_file, "r", encoding="utf-8") as f:
        data = json.load(f)
        
    with col1:
        st.subheader("📊 Latest Session Metrics")
        st.metric(label="📅 Session Timestamp", value=data.get("session_date", "N/A"))
        st.metric(label="⏱️ Duration (Seconds)", value=data.get("duration_seconds", 0))
        st.metric(label="⭐ Overall Focus Score", value=data.get("overall_focus_score", "100%"))
        
    with col2:
        st.subheader("⚠️ Alert Distribution")
        st.metric(label="👁️ Fatigue / Drowsiness Alerts", value=data.get("fatigue_alerts_count", 0))
        st.metric(label="🪑 Bad Posture Events", value=data.get("bad_posture_count", 0))
        st.metric(label="📈 Total Frames Monitored", value=data.get("total_frames_monitored", 0))
else:
    st.warning("⚠️ No active session report found yet. Run `python main.py` and complete a monitoring session first!")

st.markdown("---")

# --- AI Burnout Prediction Section ---
st.subheader("🧠 AI Burnout Prediction & Risk Analyzer (Scikit-Learn)")
risk_message, risk_level = predict_burnout_risk()

if "High" in risk_level:
    st.error(risk_message)
elif "Medium" in risk_level:
    st.warning(risk_message)
else:
    st.success(risk_message)

st.markdown("---")

# Historical Sessions Section from SQLite DB
st.subheader("🗂️ Historical Multi-Session Logs (SQLite DB)")
sessions = fetch_all_sessions()

if sessions:
    df_sessions = pd.DataFrame(sessions, columns=["Session Date", "Duration (s)", "Focus Score", "Fatigue Alerts", "Posture Issues"])
    st.dataframe(df_sessions, use_container_width=True)
else:
    st.info("No historical sessions recorded in the database yet. Complete a few sessions using `main.py` to see your trends here!")

st.markdown("---")

# --- LangChain Wellness Chatbot Section ---
st.subheader("💬 Ask AuraSync AI Coach (LangChain Powered)")
st.markdown("Have questions about ergonomics, posture correction, or fatigue management? Ask your AI wellness assistant below!")

if "chatbot" not in st.session_state:
    st.session_state.chatbot = WellnessChatbot()

if "chat_history" not in st.session_state:
    st.session_state.chat_history = []

# Display chat history
for message in st.session_state.chat_history:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# Chat input
user_input = st.chat_input("Ask for wellness tips (e.g., 'How do I fix my posture?')")
if user_input:
    st.session_state.chat_history.append({"role": "user", "content": user_input})
    with st.chat_message("user"):
        st.markdown(user_input)
        
    ai_response = st.session_state.chatbot.get_response(user_input)
    st.session_state.chat_history.append({"role": "assistant", "content": ai_response})
    with st.chat_message("assistant"):
        st.markdown(ai_response)