import json
import os
from datetime import datetime

class SessionAnalytics:
    def __init__(self):
        self.start_time = datetime.now()
        self.total_frames = 0
        self.fatigue_events = 0
        self.bad_posture_events = 0
        
    def log_frame(self, is_drowsy, is_bad_posture):
        self.total_frames += 1
        if is_drowsy:
            self.fatigue_events += 1
        if is_bad_posture:
            self.bad_posture_events += 1
            
    def export_report(self, filename="session_report.json"):
        end_time = datetime.now()
        duration = (end_time - self.start_time).total_seconds()
        
        # Calculate focus efficiency score
        if self.total_frames > 0:
            issues = self.fatigue_events + self.bad_posture_events
            score = max(0, int(100 - (issues / self.total_frames) * 100))
        else:
            score = 100
            
        report_data = {
            "session_date": self.start_time.strftime("%Y-%m-%d %H:%M:%S"),
            "duration_seconds": round(duration, 2),
            "total_frames_monitored": self.total_frames,
            "fatigue_alerts_count": self.fatigue_events,
            "bad_posture_count": self.bad_posture_events,
            "overall_focus_score": f"{score}%"
        }
        
        # Save to JSON with utf-8 encoding
        with open(filename, "w", encoding="utf-8") as f:
            json.dump(report_data, f, indent=4)
            
        # Export HTML report with utf-8 encoding to support emojis/special chars
        html_filename = "session_summary.html"
        html_content = f"""
        <!DOCTYPE html>
        <html>
        <head>
            <title>AuraSync AI - Session Report</title>
            <style>
                body {{ font-family: Arial, sans-serif; background-color: #f4f4f9; color: #333; padding: 20px; }}
                .container {{ max-width: 600px; background: white; padding: 30px; border-radius: 10px; box-shadow: 0 4px 8px rgba(0,0,0,0.1); }}
                h1 {{ color: #4A90E2; }}
                .metric {{ font-size: 18px; margin: 10px 0; }}
                .highlight {{ font-weight: bold; color: #2C3E50; }}
            </style>
        </head>
        <body>
            <div class="container">
                <h1>✨ AuraSync AI Session Report</h1>
                <p>Detailed telemetry and ergonomic wellness insights generated by your AI Coach.</p>
                <hr>
                <div class="metric">📅 Session Date: <span class="highlight">{report_data['session_date']}</span></div>
                <div class="metric">⏱️ Duration: <span class="highlight">{report_data['duration_seconds']} seconds</span></div>
                <div class="metric">👁️ Fatigue Alerts: <span class="highlight">{report_data['fatigue_alerts_count']}</span></div>
                <div class="metric">🪑 Bad Posture Events: <span class="highlight">{report_data['bad_posture_count']}</span></div>
                <div class="metric">⭐ Focus Efficiency Score: <span class="highlight">{report_data['overall_focus_score']}</span></div>
                <hr>
                <p><i>AuraSync AI - Professional Posture & Fatigue Monitoring System</i></p>
            </div>
        </body>
        </html>
        """
        with open(html_filename, "w", encoding="utf-8") as f:
            f.write(html_content)
            
        print(f"[ANALYTICS] Session report exported successfully to {filename} and {html_filename}!")